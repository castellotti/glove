"""`glove playwright view|status|login|reload` — the browser sidecar from the host.

`view` opens a loopback-only listener on a random port for as long as the
command runs. Each connection it accepts is checked (Host and Origin must be
this listener, so no other page in your browser, nor a DNS-rebinding one, can
use it) and then piped through `<runtime> exec -i <sidecar> socat` to
websockify on the sidecar's own loopback. Nothing is published and no port
outlives the command. The VNC password (generated by the sidecar at start, on
its tmpfs) is read into memory and handed to noVNC in the URL fragment, which
the browser never sends to a server.

`login` starts a dedicated Chrome on this machine (a fresh profile, deleted
afterwards; CDP over a pipe, no port) at `login.start_url`. You sign in (a
client certificate from your Keychain works, since this is your machine's
Chrome); then glove reads, over CDP, the cookies and open tabs' localStorage,
keeps only `login.domains`' hosts (`storage_state`) and the named
`login.capture` values, and writes each to the Keychain on stdin. Nothing is
printed, put in argv or written to a file. `reload` then recreates the
sidecar, which starts from the stored session.
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import shutil
import subprocess
import time
import webbrowser
from pathlib import Path

import typer
from rich.console import Console

from glove.api import ConfigError, ExtSession, ext_session, keychain_set, reload_sidecar, resolve_secret

app = typer.Typer(add_completion=False,
                  help="The playwright browser: watch or drive it (novnc), sign in on the host and hand the "
                       "session over.")
console = Console(highlight=False)
err = Console(stderr=True)

DIR_OPT = typer.Option(None, "--dir", help="session directory (default: the nearest one)")
WEBSOCKIFY = "TCP4:127.0.0.1:6080"
MAX_HEAD = 16384


def _fail(msg: str) -> typer.Exit:
    err.print(f"[red]error:[/red] {msg}")
    return typer.Exit(1)


def _session(directory: Path | None, *, launched: bool = True) -> ExtSession:
    try:
        return ext_session("playwright", directory, launched=launched)
    except ConfigError as e:
        raise _fail(str(e)) from e


def allowed(head: bytes, port: int) -> bool:
    """A request may use the tunnel only if it names this listener as its Host
    and, when it carries an Origin (every WebSocket from a page does), comes
    from it too."""
    try:
        lines = head.decode("latin-1").split("\r\n")
    except UnicodeDecodeError:  # pragma: no cover - latin-1 decodes any bytes
        return False
    headers: dict[str, str] = {}
    for line in lines[1:]:
        k, sep, v = line.partition(":")
        if sep:
            headers.setdefault(k.strip().lower(), v.strip())
    me = f"127.0.0.1:{port}"
    if headers.get("host") != me:
        return False
    return "origin" not in headers or headers["origin"] == f"http://{me}"


def view_url(port: int, password: str, *, control: bool) -> str:
    """noVNC's URL: every setting, the password included, in the fragment."""
    return (f"http://127.0.0.1:{port}/vnc.html#autoconnect=1&resize=scale&reconnect=1"
            f"&view_only={0 if control else 1}&password={password}")


async def _pipe(reader: asyncio.StreamReader, writer) -> None:
    try:
        while data := await reader.read(65536):
            writer.write(data)
            await writer.drain()
    except (ConnectionError, BrokenPipeError):
        pass
    finally:
        with contextlib.suppress(Exception):  # best effort, either side may be gone
            writer.close()


async def _serve(runtime: str, container: str, password: str, *, control: bool, open_browser: bool) -> None:
    port = 0

    async def handle(reader: asyncio.StreamReader, writer: asyncio.StreamWriter) -> None:
        try:
            head = await reader.readuntil(b"\r\n\r\n")
        except (asyncio.IncompleteReadError, asyncio.LimitOverrunError):
            writer.close()
            return
        if not allowed(head, port):
            writer.write(b"HTTP/1.1 403 Forbidden\r\nContent-Length: 0\r\nConnection: close\r\n\r\n")
            await writer.drain()
            writer.close()
            return
        proc = await asyncio.create_subprocess_exec(
            runtime, "exec", "-i", container, "socat", "STDIO", WEBSOCKIFY,
            stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.DEVNULL)
        assert proc.stdin is not None and proc.stdout is not None
        proc.stdin.write(head)
        await asyncio.gather(_pipe(reader, proc.stdin), _pipe(proc.stdout, writer))
        if proc.returncode is None:
            proc.kill()
        await proc.wait()

    server = await asyncio.start_server(handle, "127.0.0.1", 0, limit=MAX_HEAD)
    port = server.sockets[0].getsockname()[1]
    url = view_url(port, password, control=control)
    console.print(f"[bold]{'controlling' if control else 'watching'}[/bold] {container} on "
                  f"http://127.0.0.1:{port}/ (loopback only; Ctrl-C closes it)")
    if open_browser:
        webbrowser.open(url)
    else:
        console.print(f"open: {url}", soft_wrap=True)
    async with server:
        await server.serve_forever()


@app.command("view")
def view(
    directory: Path | None = DIR_OPT,
    control: bool = typer.Option(False, "--control", help="take control (needs allow_control: true)"),
    no_open: bool = typer.Option(False, "--no-open", help="print the URL instead of opening it"),
) -> None:
    """Watch the novnc browser in your own browser, through a transient loopback tunnel."""
    s = _session(directory)
    runtime, container, pw = s.runtime, s.container("pw"), s.settings
    if pw["mode"] != "novnc":
        raise _fail("`view` needs `playwright: {mode: novnc}` (this session's browser has no display)")
    if control and pw["allow_control"] is not True:
        raise _fail("--control needs `allow_control: true` in the session's playwright settings")
    if not s.running("pw"):
        raise _fail(f"{container} is not running — `glove up` first")
    r = subprocess.run([runtime, "exec", container, "cat", f"/tmp/vnc/{'full' if control else 'view'}"],
                       capture_output=True, text=True)
    if r.returncode != 0 or not r.stdout.strip():
        raise _fail(f"cannot read the VNC password from {container}")
    try:
        asyncio.run(_serve(runtime, container, r.stdout.strip(), control=control, open_browser=not no_open))
    except KeyboardInterrupt:
        console.print("closed")


@app.command("status")
def status(directory: Path | None = DIR_OPT) -> None:
    """The browser mode and whether its sidecar is running."""
    s = _session(directory)
    mode = s.settings["mode"]
    if mode == "host":
        console.print("mode host: the browser runs on this machine (host services)")
        return
    console.print(f"mode {mode}: {s.container('pw')} {'running' if s.running('pw') else 'not running'}")
    if s.settings.get("storage_state"):
        console.print(_state_status(s, s.settings["storage_state"]))


def _state_status(s: ExtSession, ref: str) -> str:
    """The stored session's cookie lifetimes (never a value)."""
    from .host import login as lg

    try:
        n, session, first = lg.expiry(s.hooks.load_state(ref, resolve_secret))
    except (ConfigError, ValueError) as e:
        return f"storage_state {ref}: [red]unreadable[/red] ({str(e)[:120] or 'not a storage state'})"
    head = f"storage_state {ref}: {n} cookie(s), {session} for the browser session only"
    if first is None:
        return head
    when = time.strftime("%Y-%m-%d %H:%M", time.localtime(first))
    left = first - time.time()
    if left <= 0:
        return f"{head}; [red]the first expired at {when}[/red] (`glove playwright login`)"
    return f"{head}; the first expires at {when} (in {left / 3600:.1f} h)"


@app.command("login")
def login(
    directory: Path | None = DIR_OPT,
    keep_profile: bool = typer.Option(False, "--keep-profile",
                                      help="keep the login browser's profile (under .glove/) for the next login"),
    no_reload: bool = typer.Option(False, "--no-reload", help="store only; don't recreate the browser sidecar"),
    headless: bool = typer.Option(False, "--headless", hidden=True,
                                  help="no window (tests: the page signs itself in)"),
    chrome_args: list[str] = typer.Option([], "--chrome-arg", hidden=True,
                                          help="an extra Chrome flag (repeatable)"),
) -> None:
    """Sign in with a dedicated Chrome on this machine, then store the session
    (storage_state) and the named values (login.capture) in the Keychain."""
    from .host import cdp
    from .host import chrome as host_chrome
    from .host import login as lg

    s = _session(directory, launched=False)
    try:
        spec = s.hooks.login_spec(s.settings)
    except ValueError as e:
        raise _fail(str(e)) from e
    if spec is None:
        raise _fail(f"{s.file}: set playwright.login (start_url, domains, capture) first")
    exe = host_chrome.chrome_executable()
    if exe is None:
        raise _fail("no Chrome/Chromium on this machine (`npx playwright install chromium`)")
    state = s.state_dir()
    profile = state / "login-profile"   # never bound into a container
    # where a kept profile (signed-in cookies) lived before api 2: moved here
    # under --keep-profile, else never left behind (TODO R19.G: drop)
    legacy = s.root / ".glove" / "playwright-login"
    if legacy.is_dir() and keep_profile and not profile.exists():
        legacy.rename(profile)
    shutil.rmtree(legacy, ignore_errors=True)
    if profile.exists() and not keep_profile:
        shutil.rmtree(profile)
    profile.mkdir(mode=0o700, exist_ok=True)
    args = [f"--user-data-dir={profile}", "--no-first-run", "--no-default-browser-check", *chrome_args]
    if headless:
        args += ["--headless=new", "--use-mock-keychain"]
    chrome = cdp.PipeChrome(exe, [*args, spec.start_url])
    try:
        console.print(f"[bold]Sign in[/bold] in the Chrome window that opened at {spec.start_url} (a profile of "
                      "its own: your Chrome is untouched). Leave open the tabs whose localStorage is captured.")
        while True:
            try:
                input("Press Enter when you are signed in (Ctrl-C: store nothing) ")
            except (EOFError, KeyboardInterrupt) as e:
                raise _fail("stopped; nothing stored") from e
            try:
                cookies = cdp.cookies(chrome)
                storage = cdp.local_storage(chrome, spec.wants_storage) if spec.needs_storage else {}
                export = lg.export_state(cookies, storage, spec.domains) if spec.state_service else None
                values = lg.captures(spec.captures, cookies, storage)
                if export is not None and not export.state["cookies"]:
                    raise lg.LoginError(f"no cookie for {', '.join(spec.domains)} yet")
            except (lg.LoginError, cdp.CDPError) as e:
                err.print(f"[yellow]not yet:[/yellow] {e}")
                continue
            break
    finally:
        chrome.close()
        if not keep_profile:
            shutil.rmtree(profile, ignore_errors=True)
    labels = {c.service: c.describe() for c in spec.captures}
    if export is not None:
        values[spec.state_service] = json.dumps(export.state, separators=(",", ":"))
        labels[spec.state_service] = export.summary
    for service, value in values.items():
        try:
            rc = keychain_set(service, value)
        except ConfigError as e:
            raise _fail(f"{service}: {e}") from e
        if rc != 0:
            raise _fail(f"storing {service} failed (exit {rc})")
        console.print(f"[green]✓[/green] {service}: {labels[service]}")
    if export is not None and export.dropped:
        console.print("[dim]left out (not in login.domains): "
                      + ", ".join(f"{k} ({n})" for k, n in sorted(export.dropped.items())) + "[/dim]")
    if spec.captures:
        console.print("[dim]a plugin relay using a captured value: `glove skills reload <plugin>`[/dim]")
    if export is not None and not no_reload:
        _reload_if_running(s)


@app.command("reload")
def reload(directory: Path | None = DIR_OPT) -> None:
    """Recreate the browser sidecar with the stored session read again
    (after `glove playwright login`); the agent's conversation keeps going."""
    if not _reload_if_running(_session(directory, launched=False)):
        raise typer.Exit(1)


def _reload_if_running(s: ExtSession) -> bool:
    if s.id is None or not s.running("pw"):
        console.print("[dim]the browser sidecar is not running: the next `glove up` starts it with the stored "
                      "session[/dim]")
        return False
    ref = s.settings.get("storage_state")
    if not ref or "PW_STORAGE_STATE" not in (s.rendered("pw").get("environment") or {}):
        err.print("[red]error:[/red] the running sidecar was started without storage_state; `glove up` applies it")
        return False
    try:
        reload_sidecar(s, "pw", s.hooks.state_env(ref, resolve_secret), wait=90)
    except (ConfigError, ValueError) as e:
        err.print(f"[red]error:[/red] {e}")
        return False
    console.print(f"[green]✓[/green] {s.container('pw')} recreated: new pages start from the stored session")
    return True
